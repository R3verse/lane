const { contextBridge, ipcRenderer } = require('electron');
contextBridge.exposeInMainWorld('lane', {
  snapshot: () => ipcRenderer.invoke('lane:snapshot'),
  ready: () => ipcRenderer.invoke('lane:renderer-ready'),
  conversation: id=>ipcRenderer.invoke('lane:conversation',id),
  onAttention: callback=>ipcRenderer.on('lane:attention',(_event,focused)=>callback(focused)),
  exportCertificate: ()=>ipcRenderer.invoke('lane:export-certificate'),
  saveRecovery: data=>ipcRenderer.invoke('lane:save-recovery',data),
  setupQR: address=>ipcRenderer.invoke('lane:setup-qr',address),
  openNearby: id => ipcRenderer.invoke('lane:open-nearby',id),
  onLaunchAction: callback => ipcRenderer.on('lane:launch-action',(_event,request)=>callback(request)),
  pair: () => ipcRenderer.invoke('lane:pair'),
  closePairing: () => ipcRenderer.invoke('lane:close-pairing'),
  qr: address => ipcRenderer.invoke('lane:qr', address),
  chooseFiles: () => ipcRenderer.invoke('lane:choose-files'),
  sendFiles: (deviceId, selectionId) => ipcRenderer.invoke('lane:send-files', deviceId, selectionId),
  messages: (deviceId, revision, limit) => ipcRenderer.invoke('lane:messages', deviceId, revision, limit),
  sendMessage: (deviceId, body) => ipcRenderer.invoke('lane:send-message', deviceId, body),
  acknowledgeMessages: (deviceId, body) => ipcRenderer.invoke('lane:ack-messages', deviceId, body),
  copyMessage: (deviceId, id, mode) => ipcRenderer.invoke('lane:copy-message', deviceId, id, mode),
  copyContent: body => ipcRenderer.invoke('lane:copy-content', body),
  saveContent: body => ipcRenderer.invoke('lane:save-content', body),
  saveMessage: (deviceId, id) => ipcRenderer.invoke('lane:save-message', deviceId, id),
  clearMessages: deviceId => ipcRenderer.invoke('lane:clear-messages', deviceId),
  reactMessage: (deviceId, id, emoji) => ipcRenderer.invoke('lane:react-message', deviceId, id, emoji),
  revoke: id => ipcRenderer.invoke('lane:revoke', id),
  cancel: id => ipcRenderer.invoke('lane:cancel', id),
  clearHistory: () => ipcRenderer.invoke('lane:clear-history'),
  chooseFolder: () => ipcRenderer.invoke('lane:choose-folder'),
  addDestination: name=>ipcRenderer.invoke('lane:add-destination',name),
  removeDestination: id=>ipcRenderer.invoke('lane:remove-destination',id),
  muteConversation: (id,muted)=>ipcRenderer.invoke('lane:mute-conversation',id,muted),
  saveDiagnostics: report=>ipcRenderer.invoke('lane:save-diagnostics',report),
  settings: patch => ipcRenderer.invoke('lane:settings', patch),
  setIdentityPublicKey: key => ipcRenderer.invoke('lane:set-identity-public-key', key),
  openFolder: () => ipcRenderer.invoke('lane:open-folder'),
  reveal: id => ipcRenderer.invoke('lane:reveal', id),
  copyAddress: address => ipcRenderer.invoke('lane:copy-address', address),
  onChanged: callback => ipcRenderer.on('lane:changed', () => callback()),
  onMessage: callback => ipcRenderer.on('lane:message', (_event, device) => callback(device)),
  onOpenMessages: callback => ipcRenderer.on('lane:open-messages', (_event, deviceId) => callback(deviceId))
});
